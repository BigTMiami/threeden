// Builds js/data/demo/year-data.js from the year simulation (js/data/demo/year-model.js):
// a slice of the simulated community for the demo, and the year's numbers.
//
//   node scripts/build-year-demo.mjs [summary.json]
//
// The demo can't run the whole simulation on page load (about a second, and
// thousands of people), so this writes the part it shows: the 40 biggest
// groups still meeting at the end of the year, their members, one in eight of
// everyone else still on 3den (about 830 people in all; halved on Nov 15 so
// the saved demo fits in the browser's storage), friendships among them (up
// to 8 each), how much each person
// and group did, and the feedback themes for the 3den Community forum.

import { writeFileSync } from 'fs';
import { simulateYear, YEAR_SEED, FEEDBACK, PERSONAS } from '../js/data/demo/year-model.js';

const run = simulateYear({ seed: YEAR_SEED });
const days = run.days;
const active = (u) => u.leftDay === null;

// The groups: still meeting, biggest first, with the people still on 3den.
const chosen = run.groups
  .filter((g) => g.endedDay === null)
  .map((g) => ({ g, live: [...g.memberIds].filter((id) => active(run.users[id - 1])) }))
  .filter(({ live }) => live.length >= 6)
  .sort((a, b) => b.live.length - a.live.length)
  .slice(0, 40);

const people = new Set();
for (const { g, live } of chosen) { people.add(g.ownerId); live.forEach((id) => people.add(id)); }
// About one in eight of everyone else still on 3den too: they're in smaller groups, or just use it with friends.
for (const u of run.users) if (active(u) && u.id % 8 === 0) people.add(u.id);

// Feedback themes, with up to four people (in the slice) who said each.
const themes = run.byTheme.map((t) => {
  const voices = run.feedback.filter((f) => f.theme === t.id && people.has(f.userId));
  const seen = new Set();
  const quotes = [];
  for (const f of voices) {
    if (seen.has(f.quote) || quotes.length >= 4) continue;
    seen.add(f.quote);
    quotes.push([f.userId, f.quote, days - f.day]);
  }
  const voters = [...new Set(run.feedback.filter((f) => f.theme === t.id).map((f) => f.userId))].filter((id) => people.has(id)).slice(0, 80);
  return { id: t.id, title: t.title, kind: t.kind, ask: t.ask, status: t.status, count: t.count, people: t.people, quotes, voters, firstDaysAgo: days - Math.min(...run.feedback.filter((f) => f.theme === t.id).map((f) => f.day)) };
}).filter((t) => t.quotes.length);
for (const t of themes) for (const [id] of t.quotes) people.add(id);

// Friendships among them, at most 8 each.
const edges = [];
const degree = new Map();
for (const id of people) {
  for (const other of run.users[id - 1].friendIds) {
    if (other <= id || !people.has(other)) continue;
    if ((degree.get(id) ?? 0) >= 8 || (degree.get(other) ?? 0) >= 8) continue;
    edges.push([id, other]);
    degree.set(id, (degree.get(id) ?? 0) + 1);
    degree.set(other, (degree.get(other) ?? 0) + 1);
  }
}

const personas = Object.keys(PERSONAS);
const data = {
  days,
  // [id, persona index, source, joined days ago, satisfaction 0–100, inviter id (in the slice) or 0, still on 3den? 1/0, days active, events hosted]
  people: [...people].sort((a, b) => a - b).map((id) => {
    const u = run.users[id - 1];
    return [id, personas.indexOf(u.persona), u.source, days - u.joinedDay, Math.round(u.satisfaction * 100), people.has(u.inviterId) ? u.inviterId : 0, active(u) ? 1 : 0, u.activeDays, u.hosted];
  }),
  // [id, kind, owner id, public 1/0, created days ago, meetings, member ids, posts, events, threads, articles]
  groups: chosen.map(({ g, live }) => [g.id, g.kind, g.ownerId, g.public ? 1 : 0, days - g.createdDay, g.meetings, live, g.posts, g.events, g.threads, g.articles]),
  friendships: edges,
  themes,
  totals: run.totals,
};

const header = `// Generated by scripts/build-year-demo.mjs from the year simulation (js/data/demo/year-model.js, seed ${YEAR_SEED}).
// Don't edit by hand: change the model and run \`node scripts/build-year-demo.mjs\` again.
// A slice of the simulated community: ${data.people.length} people, ${data.groups.length} groups, ${data.friendships.length} friendships, ${data.themes.length} feedback themes.
`;
writeFileSync(new URL('../js/data/demo/year-data.js', import.meta.url), `${header}export const YEAR_DATA = ${JSON.stringify(data)};\n`);

// The full summary, for the report.
const out = process.argv[2];
if (out) {
  const { users, groups, feedback, ...summary } = run;
  writeFileSync(out, JSON.stringify({ ...summary, feedbackSample: feedback.slice(0, 50) }, null, 1));
}
console.log(`people ${data.people.length}, groups ${data.groups.length}, friendships ${edges.length}, themes ${themes.length}; size ${(JSON.stringify(data).length / 1024).toFixed(0)} KB`);
