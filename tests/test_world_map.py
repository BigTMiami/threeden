from playwright.sync_api import sync_playwright
import os; os.makedirs('test-output', exist_ok=True)
errs=[]
with sync_playwright() as p:
    b=p.chromium.launch(executable_path='/usr/bin/google-chrome', args=['--no-sandbox'])
    for vw in [1300,400]:
        ctx=b.new_context(viewport={'width':vw,'height':900}, has_touch=(vw==400))
        pg=ctx.new_page(); pg.on('pageerror', lambda e: errs.append(str(e)))
        pg.goto('http://localhost:8765/index.html'); pg.evaluate('localStorage.clear(); sessionStorage.clear()'); pg.reload(); pg.wait_for_timeout(900)
        pg.evaluate("location.hash='#account-privacy'"); pg.wait_for_timeout(800)
        m=pg.locator('.area-map').first; m.scroll_into_view_if_needed()
        print(vw,'summary:', m.locator('.area-map__summary').inner_text().replace('\n',' '), '| labels:', m.locator('.area-map__label').count())
        m.screenshot(path=f'test-output/map_local_{vw}.png')
        m.get_by_role('button', name='See the whole world').click(); pg.wait_for_timeout(200)
        m.screenshot(path=f'test-output/map_world_{vw}.png'); print(' world labels:', m.locator('.area-map__label').count())
        s=m.locator('.area-map__search'); s.fill('pari'); pg.wait_for_timeout(200)
        print(' suggestions:', m.locator('.area-map__suggestion').all_inner_texts())
        m.locator('.area-map__suggestion').first.click(); pg.wait_for_timeout(200)
        print(' after Paris:', m.locator('.area-map__summary').inner_text().replace('\n',' ')[:60])
        m.locator('.area-map__radius').select_option('25'); pg.wait_for_timeout(200)
        m.screenshot(path=f'test-output/map_paris_{vw}.png')
        box=m.locator('.area-map__svg').bounding_box()
        if vw==1300:
            pg.mouse.move(box['x']+100,box['y']+100); pg.mouse.down(); pg.mouse.move(box['x']+300,box['y']+160,steps=5); pg.mouse.up(); pg.wait_for_timeout(200)
            print(' after drag:', m.locator('.area-map__summary').inner_text().replace('\n',' ')[:70])
            pg.mouse.move(box['x']+300,box['y']+150); pg.mouse.wheel(0,-600); pg.wait_for_timeout(200)
            hb=m.locator('.area-map__handle').bounding_box(); pg.mouse.move(hb['x']+9,hb['y']+9); pg.mouse.down(); pg.mouse.move(hb['x']-40,hb['y']+9,steps=4); pg.mouse.up(); pg.wait_for_timeout(200)
            print(' radius after handle drag:', m.locator('.area-map__radius').input_value())
        s.fill('tokyo'); pg.keyboard.press('Enter'); pg.wait_for_timeout(200)
        m.get_by_role('button', name='Save my area').click() if m.get_by_role('button', name='Save my area').count() else m.locator('.button--primary').click()
        pg.wait_for_timeout(400)
        print(' saved:', pg.evaluate("(async()=>{const s=await import('./js/state/store.js'); return JSON.stringify(s.getCurrentUser().location)})()"))
        t=pg.evaluate("""(async()=>{const m=await import('./js/ui/area-map.js'); const topo={type:'Topology',transform:{scale:[0.1,0.1],translate:[-10,40]},objects:{w:{type:'GeometryCollection',geometries:[{type:'Polygon',arcs:[[0,-2]]},{type:'MultiPolygon',arcs:[[[1]]]}]}},arcs:[[[0,0],[10,0],[0,10]],[[10,10],[-10,0],[0,-10]]]}; return JSON.stringify(m.ringsFromTopology(topo))})()""")
        print(' topo decode:', t)
        ctx.close()
    print('errors', errs)
