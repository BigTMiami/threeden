from playwright.sync_api import sync_playwright
import os; os.makedirs('test-output', exist_ok=True)
import os; os.makedirs('test-output/out', exist_ok=True)
errs=[]
def ev(pg, js): return pg.evaluate(f"(async()=>{{const a=await import('./js/state/accounts.js'); const s=await import('./js/state/store.js'); const e=await import('./js/state/events.js'); {js} }})()")
with sync_playwright() as p:
    b=p.chromium.launch(executable_path='/usr/bin/google-chrome', args=['--no-sandbox'])
    pg=b.new_page(viewport={'width':1300,'height':900}); pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.goto('http://localhost:8765/index.html'); pg.evaluate('localStorage.clear(); sessionStorage.clear()')
    pg.reload(); pg.wait_for_selector('.app-bar', timeout=20000)
    # 1. A new account with no link: two seconds of welcome, then their homepage
    ev(pg, "a.signOut(); return 1"); pg.wait_for_timeout(300)
    pg.evaluate("location.hash='#signup'"); pg.wait_for_timeout(600)
    pg.get_by_label('Your name').fill('Rosa Diaz'); pg.get_by_label('Username').fill('rosad'); pg.get_by_label('Email').fill('rosa@example.org'); pg.get_by_label('Password').fill('correct horse battery')
    pg.get_by_role('button', name='Create account').click(); pg.wait_for_timeout(400)
    splash=pg.locator('.welcome-splash')
    print('splash:', splash.count(), '|', splash.inner_text() if splash.count() else '', '| drawing:', pg.locator('.welcome-splash__tree').count())
    if not splash.count() or 'Welcome back to 3den' not in splash.inner_text(): errs.append('no welcome splash')
    print('no question:', pg.locator('.welcome__choice').count() == 0)
    pg.screenshot(path='test-output/welcome-splash.png')
    pg.wait_for_timeout(2600)
    print('after 3 s: splash gone:', pg.locator('.welcome-splash').count() == 0, '| on:', pg.evaluate('location.hash'), '| homepage modules:', pg.locator('.module-frame').count())
    if pg.locator('.welcome-splash').count(): errs.append('splash should fade after 2 s')
    pg.reload(); pg.wait_for_timeout(900)
    print('only once:', pg.locator('.welcome-splash').count() == 0)
    # 6. a quick account, after its second RSVP
    ev(pg, "a.signOut(); const m=a.createQuickAccount({name:'Sam Guest', contact:'555 123 4567'}); a.signIn(m.id); return m.id"); pg.wait_for_timeout(400)
    ids=ev(pg, "return e.getPublicEvents().filter(o=>!o.event.capacity).slice(0,2).map(o=>o.event.id)"); print('events:', ids)
    pg.evaluate(f"location.hash='#event-{ids[0]}'"); pg.wait_for_timeout(700)
    pg.locator('.event-page__rsvp .rsvp__button').first.click(); pg.wait_for_timeout(400)
    print('after 1st:', pg.locator('.toast').last.inner_text().replace('\n',' | '), '| nudge:', pg.locator('.full-account-nudge').count())
    pg.evaluate(f"location.hash='#event-{ids[1]}'"); pg.wait_for_timeout(700)
    pg.locator('.event-page__rsvp .rsvp__button').nth(1).click(); pg.wait_for_timeout(400)
    print('after 2nd:', pg.locator('.toast').last.inner_text().replace('\n',' | '), '| nudge:', pg.locator('.full-account-nudge').inner_text().replace('\n',' | ') if pg.locator('.full-account-nudge').count() else 0)
    pg.screenshot(path='test-output/full-account-nudge.png')
    pg.locator('.full-account-nudge').get_by_role('button', name='Not now').click(); pg.wait_for_timeout(300)
    print('after not now:', pg.locator('.full-account-nudge').count())
    print('errors', errs[:3])
    b.close()
