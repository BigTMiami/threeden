from playwright.sync_api import sync_playwright
import os; os.makedirs('test-output', exist_ok=True)
errs=[]
with sync_playwright() as p:
    b=p.chromium.launch(executable_path='/usr/bin/google-chrome', args=['--no-sandbox'])
    for vw in [1300,400]:
        pg=b.new_page(viewport={'width':vw,'height':900}); pg.on('pageerror', lambda e: errs.append(str(e)))
        pg.goto('http://localhost:8765/index.html'); pg.evaluate('localStorage.clear()'); pg.reload(); pg.wait_for_timeout(500)
        pg.evaluate("location.hash='#account-feed'"); pg.wait_for_timeout(600)
        sec=pg.locator('#instagram-settings'); print(vw,'section:', sec.count(), flush=True)
        sec.get_by_role('button', name='Connect Instagram').click(); pg.wait_for_timeout(300)
        d=pg.locator('.ig-connect')
        d.get_by_role('button',name='Continue with Instagram').click(); pg.wait_for_timeout(200); print(' bad handle stays step1:', d.locator('.is-current').inner_text())
        d.locator('input[type=text]').fill('@Leo.Bikes'); d.get_by_role('button',name='Continue with Instagram').click(); pg.wait_for_timeout(200)
        print(' radios:', d.locator('input[type=radio]').count(), d.locator('.radio-row').all_inner_texts())
        d.locator('input[type=radio]').last.check()
        d.get_by_role('button',name='Copy my posts').click(); pg.wait_for_timeout(400)
        print(' step:', d.locator('.is-current').inner_text())
        pg.screenshot(path=f'test-output/t118a_{vw}.png')
        d.get_by_role('button',name='Try a sample').click(); pg.wait_for_timeout(300)
        print(' result:', d.locator('.ig-connect__ok').inner_text(), '| people:', d.locator('.friend-row__name').all_inner_texts())
        pg.screenshot(path=f'test-output/t118b_{vw}.png')
        d.get_by_role('link',name='Show them to me now').click(); pg.wait_for_timeout(600)
        print(' friends IG rows:', pg.locator('#friends-instagram .friend-row').count())
        pg.locator('#friends-instagram').get_by_role('button',name='Not now').first.click(); pg.wait_for_timeout(300)
        print(' after dismiss:', pg.locator('#friends-instagram .friend-row').count())
        pg.locator('#friends-instagram').get_by_role('button',name='Add friend').first.click(); pg.wait_for_timeout(300)
        print(' after add:', pg.locator('#friends-instagram .friend-row').count())
        # blog has feed with posts
        r=pg.evaluate("""(async()=>{const s=await import('./js/state/store.js'); const me=s.getCurrentUser(); const b=s.getBlogOf(me.id); const m=b.modules.find(x=>x.title==='From Instagram'); return [m.data.posts.length, me.instagram.handle]})()""")
        print(' blog feed posts:', r)
        # simulate time passing: sync with now+9 minutes
        r=pg.evaluate("""(async()=>{const i=await import('./js/state/instagram.js'); const s=await import('./js/state/store.js'); return i.syncInstagram(s.getCurrentUser().id, Date.now()+9*60000)})()""")
        print(' periodic sync added:', r)
        pg.evaluate("location.hash='#blog-leo'"); pg.wait_for_timeout(800)
        print(' source tags on blog:', pg.locator('.feed-post__source').count(), 'tiles:', pg.locator('.feed-module').count())
        pg.screenshot(path=f'test-output/t118c_{vw}.png', full_page=False)
        pg.evaluate("location.hash='#account-feed'"); pg.wait_for_timeout(500)
        print(' acct desc:', pg.locator('#instagram-settings .settings-section__description').inner_text())
        pg.locator('#instagram-settings summary').click(); pg.locator('#instagram-settings').get_by_role('button',name='Remove them').click(); pg.wait_for_timeout(300)
        r=pg.evaluate("""(async()=>{const s=await import('./js/state/store.js'); const me=s.getCurrentUser(); const m=s.getBlogOf(me.id).modules.find(x=>x.title==='From Instagram'); return [m.data.posts.length, !!me.instagram]})()""")
        print(' after disconnect:', r)
    print('errors', errs)
