from playwright.sync_api import sync_playwright
import os; os.makedirs('test-output', exist_ok=True)
import os, re; os.makedirs('test-output/out', exist_ok=True)
errs=[]
with sync_playwright() as p:
    b=p.chromium.launch(executable_path='/usr/bin/google-chrome', args=['--no-sandbox'])
    ctx=b.new_context(viewport={'width':1300,'height':900}, accept_downloads=True); ctx.grant_permissions(['clipboard-read','clipboard-write'])
    pg=ctx.new_page(); pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.goto('http://localhost:8765/index.html'); pg.evaluate('localStorage.clear(); sessionStorage.clear()')
    pg.reload(); pg.wait_for_selector('.app-bar', timeout=20000)
    pg.evaluate("location.hash='#account-calendars'"); pg.wait_for_timeout(700)
    sec=pg.locator('#calendar-feed')
    print('before:', sec.inner_text().replace('\n',' | ')[:160])
    sec.get_by_role('button', name='Set it up').click(); pg.wait_for_timeout(400)
    sec=pg.locator('#calendar-feed')
    hrefs={a.inner_text(): a.get_attribute('href') for a in sec.locator('.calendar-feed__apps a').all()}
    for k,v in hrefs.items(): print(' ', k, '→', v[:95])
    print('google has cid webcal:', 'cid=webcal%3A%2F%2F3den.example%2Fcal%2F' in hrefs['Add to Google Calendar'])
    print('count line:', sec.locator('.calendar-feed__count').inner_text())
    sec.locator('summary').click(); pg.wait_for_timeout(150)
    addr=sec.locator('input[aria-label="Calendar address"]').input_value(); print('address:', re.sub(r'[0-9a-f]{24}', '<token>', addr))
    sec.get_by_role('button', name='Copy').click(); pg.wait_for_timeout(200)
    print('copied ok:', pg.evaluate('navigator.clipboard.readText()')==addr)
    with pg.expect_download() as dl: sec.get_by_role('button', name='Download them as a file').click()
    t=open(dl.value.path()).read()
    n1=t.count('BEGIN:VEVENT'); print('ics events:', n1, '| refresh:', 'REFRESH-INTERVAL;VALUE=DURATION:PT1H' in t, '| url:', 'URL:https://3den.example/#event-' in t, '| tentative:', t.count('STATUS:TENTATIVE'))
    pg.screenshot(path='test-output/calendar-feed.png', full_page=False)
    # maybe too
    sec.get_by_label('Those, and ones I said maybe to').check(); pg.wait_for_timeout(300)
    print('count with maybe:', pg.locator('#calendar-feed .calendar-feed__count').inner_text())
    with pg.expect_download() as dl: pg.locator('#calendar-feed').get_by_role('button', name='Download them as a file').click()
    t2=open(dl.value.path()).read(); print('with maybe events:', t2.count('BEGIN:VEVENT'), 'tentative:', t2.count('STATUS:TENTATIVE'))
    # new address
    pg.locator('#calendar-feed').get_by_role('button', name='Make a new address').click(); pg.wait_for_timeout(300)
    pg.locator('#calendar-feed summary').click()
    addr2=pg.locator('#calendar-feed input[aria-label="Calendar address"]').input_value(); print('new address differs:', addr2!=addr)
    # stop + undo
    pg.locator('#calendar-feed').get_by_role('button', name='Stop sharing').click(); pg.wait_for_timeout(300)
    print('after stop:', pg.locator('#calendar-feed').get_by_role('button', name='Set it up').count())
    pg.locator('.toast').get_by_role('button', name='Undo').click(); pg.wait_for_timeout(300)
    pg.locator('#calendar-feed summary').click()
    print('undo keeps address:', pg.locator('#calendar-feed input[aria-label="Calendar address"]').input_value()==addr2)
    # link from My calendar
    home=pg.evaluate("(async()=>{const s=await import('./js/state/store.js'); const me=s.getCurrentUser(); const sp=s.getSpaces().find(x=>x.kind==='personal'&&x.memberIds[0]===me.id); return sp.modules.find(m=>m.type==='calendar')?.id})()")
    pg.evaluate(f"location.hash='#module-{home}'"); pg.wait_for_timeout(800)
    print('my calendar link:', pg.locator('a[aria-label="Show in Google or Apple Calendar"]:visible').count())
    pg.set_viewport_size({'width':400,'height':800}); pg.evaluate("location.hash='#account-calendars'"); pg.wait_for_timeout(600)
    pg.screenshot(path='test-output/calendar-feed-phone.png', full_page=False)
    print('phone overflow:', pg.evaluate('document.documentElement.scrollWidth > innerWidth'))
    print('errors', errs[:3])
    b.close()
