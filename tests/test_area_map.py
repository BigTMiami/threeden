from playwright.sync_api import sync_playwright
import os; os.makedirs('test-output', exist_ok=True)
errs=[]
with sync_playwright() as p:
    b=p.chromium.launch(executable_path='/usr/bin/google-chrome', args=['--no-sandbox'])
    for vw,touch in [(1300,False),(400,True)]:
        ctx=b.new_context(viewport={'width':vw,'height':900}, has_touch=touch)
        pg=ctx.new_page(); pg.on('pageerror', lambda e: errs.append(str(e)))
        pg.goto('http://localhost:8765/index.html'); pg.evaluate('localStorage.clear()'); pg.reload(); pg.wait_for_timeout(500)
        pg.evaluate("(async()=>{const a=await import('./js/state/accounts.js');const s=await import('./js/state/store.js');a.updateProfile(s.getCurrentUser().id,{location:null});location.hash='#groups-explore'})()"); pg.wait_for_timeout(700)
        sv=pg.locator('#settings-view')
        print(vw, 'gate:', sv.locator('.explore-area').count(), '| event rows shown:', sv.locator('.explore-events li').count())
        sv.locator('.area-map__search').fill('river'); pg.wait_for_timeout(100)
        print(' suggestions:', sv.locator('.area-map__suggestion').all_inner_texts())
        sv.locator('.area-map__suggestion').first.click(); pg.wait_for_timeout(100)
        print(' summary:', sv.locator('.area-map__summary').inner_text())
        h=sv.locator('.area-map__handle'); bb=h.bounding_box()
        pg.mouse.move(bb['x']+bb['width']/2, bb['y']+bb['height']/2); pg.mouse.down(); pg.mouse.move(bb['x']+bb['width']/2+60, bb['y']+bb['height']/2, steps=5); pg.mouse.up(); pg.wait_for_timeout(100)
        print(' after radius drag:', sv.locator('.area-map__summary').inner_text())
        svg=sv.locator('.area-map__svg'); sb=svg.bounding_box()
        pg.mouse.move(sb['x']+40, sb['y']+40); pg.mouse.down(); pg.mouse.move(sb['x']+140, sb['y']+60, steps=5); pg.mouse.up()
        print(' after pan:', sv.locator('.area-map__summary').inner_text())
        pg.screenshot(path=f'test-output/t114_{vw}.png')
        sv.get_by_role('button', name='Show what’s near here').click(); pg.wait_for_timeout(500)
        print(' after save: gate', sv.locator('.explore-area').count(), '| where:', sv.locator('.explore-events__where').inner_text() if sv.locator('.explore-events__where').count() else '-', '| rows:', sv.locator('.explore-events li').count())
        pg.evaluate("location.hash='#account'"); pg.wait_for_timeout(500)
        print(' account map:', sv.locator('#location-settings .area-map').count())
        ctx.close()
    b.close()
print('ERRORS', errs)
